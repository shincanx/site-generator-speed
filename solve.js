// A faster drop-in for makefun-site 1.0.0: run(input) returns exactly the answer
// makefun-site 1.0.0's build returns for the same input, as a JSON object of
// every path it writes and that file's text, byte for byte.
//
// Written from makefun-site's README and the behaviour of its reference code:
// its front matter, template dialect, Markdown subset, slug rule and report are
// its own. Same pipeline, same order, same report lines — only faster:
//   - Markdown inline rendering scans plain runs in bulk instead of one
//     regex replace per character, and the block lexer dispatches on the
//     line's first character instead of running every anchored regex.
//   - slugify memoises per build and skips NFKD for pure-ASCII text
//     (NFKD is the identity on ASCII).
//   - Front matter is scanned with indexOf instead of splitting the body.
//   - Templates are compiled once per build into plain JS functions
//     (null-prototype scope chains keep the dialect's lookup rules exact),
//     with a small tree-walking interpreter as fallback.

